import { sdkContract, type SdkCall, type SdkContract, type SdkError, type SdkModule } from "./contract";

/** The checked-in files `bun run sdk:render` writes, relative to the repository root. */
export const renderedPaths = {
  prompt: "src/agent/sdk-section.generated.ts",
  guide: "kernel-rs/konae/src/sdk-guide.json",
  docs: "docs/sdk.md",
} as const;

const generatedNotice = "Generated by `bun run sdk:render` from src/sdk/contract.ts. Edit the contract, not this file.";

function callPath(module: SdkModule, call: SdkCall) {
  return `miniapp.${module.name}.${call.name}`;
}

/** A module with calls is a namespace on miniapp; one without is only declared. */
function moduleHeading(module: SdkModule) {
  return module.calls.length ? `miniapp.${module.name}` : `The ${module.name} module, declared, with no browser call`;
}

function quoted(error: SdkError) {
  return `"${error.message}"`;
}

function exampleBlock(contract: SdkContract): string {
  const examples = contract.modules.flatMap((module) => module.calls.flatMap((call) => call.examples));
  const width = Math.max(...examples.filter((example) => example.comment).map((example) => example.code.length));
  return examples
    .map((example) => (example.comment ? `${example.code.padEnd(width)}  // ${example.comment}` : example.code))
    .join("\n");
}

function absentSentence(contract: SdkContract) {
  return `There is nothing else: ${contract.absent.join(", ")}.`;
}

const gateRefuses =
  "When the Validation Gate or a release refuses a key declared in actions.json or the manifest, validate_capsule returns its sentence, a code and the remedy. The declarations below list only the refusals a route's caller meets.";

/**
 * The SDK section of the build agent's system prompt. It is part of the cached
 * prefix, so it depends on the contract alone.
 */
export function renderPromptSection(contract: SdkContract = sdkContract): string {
  const lines = [
    "# The miniapp SDK, the only host surface",
    "",
    exampleBlock(contract),
    "",
    absentSentence(contract),
    "",
    gateRefuses,
  ];
  for (const module of contract.modules) {
    lines.push("", `## ${moduleHeading(module)}`, "", module.summary, ...module.notes);
    for (const declaration of module.declarations) {
      lines.push("", `Declared with "${declaration.key}" in ${declaration.file}: ${declaration.summary}`);
      // A wrong declaration is a Gate refusal with a code in a case file, and
      // validate_capsule returns its remedy, so the prompt keeps only what a
      // route's caller meets at runtime, which carries an HTTP status.
      const atRuntime = declaration.errors?.filter((error) => error.status !== undefined) ?? [];
      if (atRuntime.length) {
        lines.push("A route answers its caller with:");
        for (const error of atRuntime) lines.push(`- ${quoted(error)} when ${error.when}`);
      }
      if (declaration.limits?.length) lines.push("Limits:", ...declaration.limits.map((limit) => `- ${limit}`));
    }
    for (const call of module.calls) {
      lines.push("", `${call.signature}: ${call.summary} Returns ${call.returns}.`);
      if (!call.signedOut) lines.push("Needs a signed-in user.");
      if (call.errors.length) {
        lines.push("Refusals:");
        for (const error of call.errors) lines.push(`- ${quoted(error)} when ${error.when}`);
      }
      if (call.limits.length) lines.push("Limits:", ...call.limits.map((limit) => `- ${limit}`));
      if (call.preview) lines.push(`Editor preview: ${call.preview}`);
    }
  }
  lines.push("", "Any call that reaches the Kernel can also refuse with:");
  for (const error of contract.errors) lines.push(`- ${quoted(error)} when ${error.when}`);
  return lines.join("\n");
}

/** The generated TypeScript module that holds the prompt section. */
export function renderPromptModule(contract: SdkContract = sdkContract): string {
  const escaped = renderPromptSection(contract).replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
  return `// ${generatedNotice}\n\nexport const sdkPromptSection = \`${escaped}\`;\n`;
}

function guideError({ message, when, source }: SdkError) {
  return { message, when, source };
}

/**
 * The `sdk` topic of `platform_guide`. The Kernel includes this JSON with
 * include_str!, so an external agent reads the same contract as the build agent.
 * Preview differences are left out: an external agent never runs in the preview.
 */
export function renderPlatformGuide(contract: SdkContract = sdkContract): string {
  const guide = {
    generated: generatedNotice,
    global: contract.global,
    endpoint: contract.endpoint,
    summary: contract.summary,
    examples: contract.modules.flatMap((module) => module.calls.flatMap((call) => call.examples.map((example) => example.code))),
    absent: contract.absent,
    errors: contract.errors.map(guideError),
    modules: contract.modules.map((module) => ({
      name: module.name,
      summary: module.summary,
      notes: module.notes,
      declarations: module.declarations.map(({ errors, ...declaration }) => ({
        ...declaration,
        ...(errors ? { errors: errors.map(guideError) } : {}),
      })),
      calls: module.calls.map((call) => ({
        call: callPath(module, call),
        signature: call.signature,
        summary: call.summary,
        signedOut: call.signedOut,
        tools: call.tools,
        args: call.args,
        returns: call.returns,
        errors: call.errors.map(guideError),
        limits: call.limits,
      })),
    })),
  };
  return `${JSON.stringify(guide, null, 2)}\n`;
}

function cell(text: string) {
  return text.replaceAll("|", "\\|").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function previewCell(error: SdkError) {
  if (error.preview === undefined) return "Same";
  if (error.preview === null) return "Never refuses";
  return error.preview.map((message) => `\`${message}\``).join(" or ");
}

function errorTable(errors: readonly SdkError[]) {
  return [
    "| Message | When | Source | Editor preview |",
    "| --- | --- | --- | --- |",
    ...errors.map((error) => `| \`${error.message}\` | ${cell(error.when)} | ${error.source === "kernel" ? "Kernel" : "SDK"} | ${previewCell(error)} |`),
  ];
}

/** docs/sdk.md, the human-readable form of the contract. */
export function renderDocs(contract: SdkContract = sdkContract): string {
  const lines = [
    "# The miniapp SDK",
    "",
    `<!-- ${generatedNotice} -->`,
    "",
    contract.summary,
    "",
    "```js",
    exampleBlock(contract),
    "```",
    "",
    absentSentence(contract),
    "",
    "Error messages below are the exact text a published app receives as `error.message`. The Editor preview column says where the preview in the editor answers differently.",
    "",
    "## Refusals on every call",
    "",
    ...errorTable(contract.errors),
  ];
  for (const module of contract.modules) {
    lines.push("", `## ${moduleHeading(module)}`, "", module.summary);
    if (module.notes.length) lines.push("", ...module.notes.map((note) => `- ${note}`));
    for (const declaration of module.declarations) {
      lines.push("", `Declared with \`${declaration.key}\` in \`${declaration.file}\`. ${declaration.summary}`);
      if (declaration.errors?.length) lines.push("", ...errorTable(declaration.errors));
      if (declaration.limits?.length) lines.push("", "Limits:", "", ...declaration.limits.map((limit) => `- ${limit}`));
    }
    for (const call of module.calls) {
      lines.push("", `### ${call.signature}`, "", call.summary, "");
      lines.push(`Signed-out visitors on a public Deployment: ${call.signedOut ? "allowed" : "refused"}.`, "");
      lines.push(`Runtime MCP tools: ${call.tools.length ? call.tools.map((tool) => `\`${tool}\``).join(", ") : "none"}.`);
      if (call.args.length) {
        lines.push("", "| Argument | Type | Required | Description |", "| --- | --- | --- | --- |");
        for (const arg of call.args) lines.push(`| \`${arg.name}\` | \`${cell(arg.type)}\` | ${arg.required ? "Yes" : "No"} | ${cell(arg.description)} |`);
      }
      lines.push("", `Returns ${call.returns}.`);
      if (call.errors.length) lines.push("", ...errorTable(call.errors));
      if (call.limits.length) lines.push("", "Limits:", "", ...call.limits.map((limit) => `- ${limit}`));
      if (call.preview) lines.push("", `Editor preview: ${call.preview}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

/** Every rendered file keyed by its path, so the script and the test share one list. */
export function renderAll(contract: SdkContract = sdkContract): Record<string, string> {
  return {
    [renderedPaths.prompt]: renderPromptModule(contract),
    [renderedPaths.guide]: renderPlatformGuide(contract),
    [renderedPaths.docs]: renderDocs(contract),
  };
}
